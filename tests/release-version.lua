local version = dofile("tools/release-version.lua")
local checks = 0
local function selected(current, mode, custom, tags, expected)
    assert(version.select(current, mode, custom, tags) == expected)
    checks = checks + 1
end
local function rejected(current, mode, custom, tags)
    assert(not pcall(version.select, current, mode, custom, tags))
    checks = checks + 1
end
selected("0.1.16", "automatic", "", {}, "0.1.16")
selected("0.1.16", "automatic", "", { "v0.1.15" }, "0.1.16")
selected("0.1.16", "automatic", "", { "v0.1.16" }, "0.1.17")
selected("0.1.16", "automatic", "", { "v0.1.9", "v0.1.20", "v0.1.17" }, "0.1.21")
selected("0.1.16", "automatic", "", { "v9.0.0-beta", "unrelated", "v01.0.0" }, "0.1.16")
selected("0.1.16", "code", "", {}, "0.1.16")
selected("0.1.16", "patch", "", {}, "0.1.17")
selected("0.1.16", "minor", "", {}, "0.2.0")
selected("0.1.16", "major", "", {}, "1.0.0")
selected("0.1.16", "minor", "", { "v1.9.2", "v1.10.0" }, "1.11.0")
selected("0.1.16", "patch", "", { "v1.0.0" }, "1.0.1")
selected("0.1.16", "automatic", "0.1.0", {}, "0.1.0")
selected("0.1.16", "major", "0.2.3", { "v0.1.16" }, "0.2.3")
selected("0.1.16", "Automatic", "", { "v0.1.16" }, "0.1.17")
selected("0.1.16", "Use code version", "", {}, "0.1.16")
selected("0.1.16", "Patch", "", {}, "0.1.17")
selected("0.1.16", "Minor", "", {}, "0.2.0")
selected("0.1.16", "Major", "", {}, "1.0.0")
rejected("0.1.16", "code", "", { "v0.1.16" })
rejected("0.1.16", "automatic", "0.1.15", { "v0.1.16" })
rejected("0.1.16", "automatic", "0.1.16", { "v0.1.16" })
rejected("0.1.16", "unknown", "", {})
for _, bad in ipairs({ "v0.2.0", "0.2", "01.2.0", "0.2.0-beta", "0.2.-1", " 0.2.0", "0.2.0;echo broken" }) do
    rejected("0.1.16", "automatic", bad, {})
end
local path = os.tmpname()
local file = assert(io.open(path, "wb"))
file:write('return {\n    version = "0.1.16",\n    description = "Original",\n}\n')
file:close()
version.write(path, "0.2.0")
file = assert(io.open(path, "rb"))
assert(file:read("*a") == 'return {\n    version = "0.2.0",\n    description = "Original",\n}\n')
file:close()
assert(not pcall(version.write, path, "01.2.0"))
os.remove(path)
print("PASS " .. (checks + 2) .. " release-version selection and metadata checks")
